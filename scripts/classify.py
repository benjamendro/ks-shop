CAT_INDEX = {c["id"]: c for c in CATEGORIES}
SUB_PARENT = {}
for _c in CATEGORIES:
    for _sid, _ in _c["subs"]:
        SUB_PARENT[_sid] = _c["id"]

_FINALS = str.maketrans("ךםןףץ", "כמנפצ")
_QUOTES = str.maketrans({c: None for c in "\"'״׳`´“”„"})


def normalize(text: str) -> str:
    if not text:
        return ""
    text = unicodedata.normalize("NFKC", text)
    text = text.translate(_QUOTES).translate(_FINALS)
    text = text.replace("־", " ").replace("-", " ").replace("–", " ")
    text = re.sub(r"[^\w\u0590-\u05ff\s%./]+", " ", text, flags=re.UNICODE)
    text = re.sub(r"\s+", " ", text)
    return text.strip().lower()


def _hit(blob: str, words: list[str]) -> str | None:
    """Return the first keyword that appears as a substring, preferring longer."""
    for w in words:
        if w in blob:
            return w
    return None


