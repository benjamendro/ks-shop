def is_junk(name: str, price: float | None) -> bool:
    n = name or ""
    if len(n.strip()) < 2:
        return True
    if _JUNK_NAME.search(n):
        return True
    if price is not None and price <= 0:
        return True
    if price is not None and price <= 0.05 and "פיקדון" not in n:
        return True
    return False



# Pre-normalize keywords once (classify is called for tens of thousands of products).
COMPILED_RULES: list[tuple[int, str, str, int]] = []  # prio, sub, kw_norm, kwlen
for _prio, _sub, _words in RULES:
    for _w in _words:
        _wn = normalize(_w)
        if _wn and len(_wn) >= 3:
            COMPILED_RULES.append((_prio, _sub, _wn, len(_wn)))

COMPILED_NEG: dict[str, list[str]] = {
    sub: [normalize(neg) for neg in negs] for sub, negs in NEGATIVES.items()
}

