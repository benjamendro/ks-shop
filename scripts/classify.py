# Letters only — digits, %, punctuation, and Latin/Hebrew transitions are boundaries.
# So "בולגרית24%" and "32טיטולים" still match, but "ננה" does not match inside "בננה".
_LET = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZא-ת")
# The set above has a range typo as string; build properly:
_LET = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ")
_LET.update("אבגדהוזחטיכלמנסעפצקרשתךםןףץ")


def kw_hit(blob: str, kw: str) -> bool:
    start = 0
    k = len(kw)
    n = len(blob)
    while True:
        i = blob.find(kw, start)
        if i < 0:
            return False
        left_ok = i == 0 or blob[i - 1] not in _LET
        right_ok = i + k >= n or blob[i + k] not in _LET
        if left_ok and right_ok:
            return True
        start = i + 1


def _kw_in(padded: str, kw: str) -> bool:
    # padded may or may not include surrounding spaces; use raw blob-style search
    return kw_hit(padded.strip(), kw)





def _expand_abbreviations(text: str) -> str:
    reps = [
        ("גב.", "גבינה "),
        ("גבי.", "גבינה "),
        ("חמוצ.", "חמוצים "),
        ("חמצ.", "חמוצים "),
        ("נקנ.", "נקניק "),
        ("שוק'", "שוקולד "),
        ("שוק׳", "שוקולד "),
        ("שוק.", "שוקולד "),
        ('תפו"ע', "תפוח עץ "),
        ('תפו"א', "תפוחי אדמה "),
        ("טיטול", "חיתול"),
        ("טמפוני", "טמפונים "),
    ]
    for a, b in reps:
        if a in text:
            text = text.replace(a, b)
    return text


def classify(name: str, manufacturer: str = "") -> tuple[str, str, str]:
    """Return (category_id, subcategory_id, matched_keyword_or_reason)."""
    blob = normalize(_expand_abbreviations(f"{name} {manufacturer}"))
    if not blob:
        return "other", "other", "empty"

    padded = f" {blob} "
    frozen = any(tok in blob for tok in FROZEN_TOKS)

    best: tuple[int, int, str, str] | None = None  # (score, kwlen, sub, kw)
    for prio, sub, wn, ln in COMPILED_RULES:
        if not kw_hit(blob, wn):
            continue
        negs = COMPILED_NEG.get(sub)
        if negs and any(kw_hit(blob, neg) or neg in blob for neg in negs):
            continue
        score = prio * 4 + ln * 10
        cand = (score, ln, sub, wn)
        if best is None or cand[0] > best[0] or (cand[0] == best[0] and cand[1] > best[1]):
            best = cand

    # Tofu must stay in plant-based even if a flavor word hits produce/herbs (e.g. טופו בזיליקום).
    if kw_hit(blob, "טופו") or kw_hit(blob, "tofu"):
        if not frozen:
            best = (20_000, 4, "plant", "טופו")

    if frozen:
        if any(kw_hit(blob, tok) for tok in MEAT_TOKS):
            why = best[3] if best else "קפוא"
            best = (10_000, 4, "frozen_meat", why)
        elif any(kw_hit(blob, tok) for tok in PRODUCE_TOKS):
            why = best[3] if best else "קפוא"
            best = (10_000, 4, "frozen_veg", why)
        elif best and best[2] not in ("ice_cream", "frozen_veg", "frozen_meat", "frozen_ready"):
            best = (10_000, 4, "frozen_ready", best[3])

    if best is None:
        # manufacturer hints
        manu = normalize(manufacturer)
        name_n = normalize(name)
        for sub, hints in MANU_HINTS:
            if any(normalize(h) in manu or normalize(h) in name_n for h in hints):
                cat = SUB_PARENT.get(sub, "other")
                return cat, sub, "manufacturer"
        return "other", "other", "unmatched"

    sub = best[2]
    cat = SUB_PARENT.get(sub, "other")
    return cat, sub, best[3]



